def make_slug(title, idx):
    """Create a safe filename slug from title."""
    slug = title.replace(" ", "_").replace(",", "").replace("-", "_")
    slug = "".join(c for c in slug if c.isalnum() or c == "_")
    slug = slug[:50] + f"_{idx:02d}"
    return slug.lower()

def main():
    summary_dir = f"out/{TODAY}/SUMMARY_KO"
    os.makedirs(summary_dir, exist_ok=True)

    articles = json.load(open(f"/tmp/scraped_{TODAY}.json"))

    print(f"[STAGE] Writing {len(articles)} comprehensive Korean summaries...")

    written = 0
    for idx, article in enumerate(articles):
        url = article["url"]
        title = article["title"]

        if url not in SUMMARIES:
            print(f"[WARN] No summary template for {url}")
            continue

        summary_data = SUMMARIES[url]

        # Create markdown content
        content = f"""---
title: {title}
url: {url}
date: {TODAY}
section: {article.get('section', 'unknown')}
---

# {title}

## 요약
{summary_data['요약']}

## 주요 인용/수치
{summary_data['수치']}

## 시사점
{summary_data['시사점']}
"""

        # Create safe filename
        slug = make_slug(title, idx + 1)
        filepath = f"{summary_dir}/{slug}.md"

        with open(filepath, "w", encoding="utf-8") as f:
            f.write(content)

        written += 1
        print(f"[SUMMARY] {idx+1}/{len(articles)}: {slug}.md")

    print(f"[STAGE] summary_written={written}")
    return written == len(articles)

if __name__ == "__main__":
    main()
